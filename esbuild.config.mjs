import esbuild from "esbuild";
import process from "process";
import { readFile } from "fs/promises";
import { deflateSync } from "fflate";
import { fileURLToPath } from "url";

const prod = process.argv[2] === "production";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://github.com/cschiller/zhongwen (ported to Obsidian)
*/`;

// `import packed from "cedict:packed"` → CC-CEDICT packed to stay well under
// Obsidian Sync's 5 MB per-file limit (the raw text is 9.6 MB):
//   - entries are split into four columns (traditional, or "" when equal to
//     simplified / simplified / pinyin / definitions), "\n" between entries
//     and "\0" between columns, which compresses far better than whole lines;
//   - the result is raw-deflated and base64-encoded. Compression uses fflate
//     (pure JS), not Node's zlib: zlib output varies with the machine and Node
//     version, which would make main.js impossible to reproduce from source.
// No index is shipped: src/cedict.ts rebuilds it at startup.
// Unpacked by unpackCedict() in src/cedict.ts; keep both sides in sync.
const CEDICT_LINE = /^(\S+) (\S+) \[(.*?)\] \/(.*)\/$/;

async function packCedict(path) {
  const cols = [[], [], [], []];
  for (const line of (await readFile(path, "utf8")).split(/\r?\n/)) {
    if (!line || line.startsWith("#")) continue;
    const m = line.match(CEDICT_LINE);
    if (!m) throw new Error(`Unexpected CC-CEDICT line: ${line}`);
    const [, trad, simp, pinyin, defs] = m;
    cols[0].push(trad === simp ? "" : trad);
    cols[1].push(simp);
    cols[2].push(pinyin);
    cols[3].push(defs);
  }
  const payload = cols.map((c) => c.join("\n")).join("\0");
  return Buffer.from(deflateSync(Buffer.from(payload, "utf8"), { level: 9 })).toString("base64");
}

const cedictPlugin = {
  name: "cedict",
  setup(build) {
    build.onResolve({ filter: /^cedict:packed$/ }, () => ({
      path: fileURLToPath(new URL("./data/cedict_ts.u8", import.meta.url)),
      namespace: "cedict",
    }));
    build.onLoad({ filter: /.*/, namespace: "cedict" }, async (args) => ({
      contents: `export default ${JSON.stringify(await packCedict(args.path))};`,
      loader: "js",
      watchFiles: [args.path],
    }));
  },
};

const ctx = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["main.ts"],
  bundle: true,
  // Provided by Obsidian at runtime — must NOT be bundled.
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  plugins: [cedictPlugin],
  // Keep non-ASCII as raw UTF-8 instead of escape sequences (smaller main.js).
  charset: "utf8",
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

if (prod) {
  await ctx.rebuild();
  process.exit(0);
} else {
  await ctx.watch();
}
