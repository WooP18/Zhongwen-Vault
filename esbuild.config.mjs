import esbuild from "esbuild";
import process from "process";
import { readFile } from "fs/promises";

const prod = process.argv[2] === "production";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://github.com/cschiller/zhongwen (ported to Obsidian)
*/`;

// Embed the CC-CEDICT files as plain JS string literals, read byte-exact.
// JSON.stringify keeps every carriage return, so cedict.idx offsets (computed against
// the original CRLF text) stay valid. This avoids a base64 blob plus a runtime
// decoder in main.js, which plugin scanners misread as hidden code.
const rawTextPlugin = {
  name: "raw-text",
  setup(build) {
    build.onLoad({ filter: /\.(u8|idx)$/ }, async (args) => ({
      contents: `export default ${JSON.stringify(await readFile(args.path, "utf8"))};`,
      loader: "js",
    }));
  },
};

const ctx = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["main.ts"],
  bundle: true,
  // Provided by Obsidian at runtime — must NOT be bundled.
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  plugins: [rawTextPlugin],
  // Keep CJK as raw UTF-8 instead of XXXX escapes (smaller main.js).
  charset: "utf8",
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

if (prod) {
  await ctx.rebuild();
  process.exit(0);
} else {
  await ctx.watch();
}
